-- Interactive Architecture Guide (SPA-409)
-- Creates the pre-configured template stacks table used by the /architect diagnostic.
-- The marketing site data lives in the `marketing` schema (see marketing.leads/proposals).
-- This migration is idempotent so it can be safely re-run.

create schema if not exists marketing;

create table if not exists marketing.stacks (
  id               uuid primary key default gen_random_uuid(),
  name             text not null unique,
  tagline          text,
  description      text not null,
  languages        text[] not null default '{}',
  frameworks       text[] not null default '{}',
  hosting          text[] not null default '{}',
  best_for         text[] not null default '{}',
  sample_repo_url  text,
  -- Relative leanings (1-5) used both to place the stack on the priority
  -- diagram and to give the recommendation model structured hints.
  speed            int not null default 3,
  customizability  int not null default 3,
  portability      int not null default 3,
  integrated       int not null default 3,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

-- Captures leads generated by the architect diagnostic when a visitor requests
-- the PDF report by entering their email.
create table if not exists marketing.architect_leads (
  id                 uuid primary key default gen_random_uuid(),
  email              text not null,
  recommended_stack  text,
  answers            jsonb not null default '{}'::jsonb,
  report_sent        boolean not null default false,
  created_at         timestamptz not null default now()
);

create index if not exists architect_leads_email_idx on marketing.architect_leads (email);
